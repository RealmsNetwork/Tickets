import { escapeHtml } from '../utils/text.js';

export async function renderTranscript(channel, limit = 500) {
  const all = [];
  let before;
  let remaining = Math.max(1, Math.min(Number(limit) || 500, 5000));

  while (remaining > 0) {
    const batch = await channel.messages.fetch({ limit: Math.min(100, remaining), ...(before ? { before } : {}) });
    if (!batch.size) break;
    const messages = [...batch.values()];
    all.push(...messages);
    remaining -= messages.length;
    const oldest = messages.reduce((current, item) => !current || item.createdTimestamp < current.createdTimestamp ? item : current, null);
    if (!oldest || messages.length < 100) break;
    before = oldest.id;
  }

  all.sort((a, b) => a.createdTimestamp - b.createdTimestamp);
  const entries = all.map((message) => {
    const avatar = message.author?.displayAvatarURL?.({ extension: 'png', size: 64 }) ?? '';
    const attachments = [...message.attachments.values()].map((attachment) =>
      `<li><a rel="noreferrer" href="${escapeHtml(attachment.url)}">${escapeHtml(attachment.name || 'attachment')}</a></li>`).join('');
    const body = escapeHtml(message.content || '').replaceAll('\n', '<br>');
    const embedText = message.embeds.map((embed) => [embed.title, embed.description].filter(Boolean).join('\n')).filter(Boolean).join('\n\n');
    const extra = embedText ? `<div class="embed">${escapeHtml(embedText).replaceAll('\n', '<br>')}</div>` : '';
    const files = attachments ? `<ul class="attachments">${attachments}</ul>` : '';
    const image = avatar ? `<img class="avatar" src="${escapeHtml(avatar)}" alt="">` : '';
    const when = new Date(message.createdTimestamp).toISOString().replace('T', ' ').replace('Z', ' UTC');
    return `<article class="message">${image}<div class="message-content"><div class="meta"><strong>${escapeHtml(message.author?.tag || 'Unknown user')}</strong> <span>${escapeHtml(when)}</span></div><div class="body">${body || '<em>(no text content)</em>'}</div>${extra}${files}</div></article>`;
  }).join('\n');

  const html = `<!doctype html><html lang="en"><head><meta charset="utf-8"><meta name="viewport" content="width=device-width,initial-scale=1"><title>Ticket transcript — ${escapeHtml(channel.name)}</title><style>
  :root{color-scheme:dark;background:#17191f;color:#e6e8ef;font:14px/1.55 system-ui,sans-serif}body{max-width:1000px;margin:0 auto;padding:24px}header{padding:16px 0 24px;border-bottom:1px solid #343844;margin-bottom:20px}h1{font-size:21px;margin:0 0 6px}.muted,.meta span{color:#a8afc0}.message{display:flex;gap:12px;padding:14px 0;border-bottom:1px solid #2b2f3a;overflow-wrap:anywhere}.avatar{width:36px;height:36px;border-radius:50%;object-fit:cover}.message-content{min-width:0;flex:1}.meta{margin-bottom:5px}.meta span{font-size:12px;margin-left:7px}.body{white-space:normal}.embed{white-space:normal;margin-top:8px;padding:10px;border-left:3px solid #6d5ae6;background:#222631;border-radius:4px}.attachments{padding-left:18px}.attachments a{color:#a99bff}footer{margin-top:28px;color:#858b9b;font-size:12px}
  </style></head><body><header><h1>Ticket transcript</h1><div class="muted">Channel: #${escapeHtml(channel.name)} · Channel ID: ${escapeHtml(channel.id)}</div><div class="muted">Exported ${escapeHtml(new Date().toISOString())} · ${all.length} message(s)</div></header><main>${entries || '<p>No messages found.</p>'}</main><footer>Generated by RealmsNetwork Tickets.</footer></body></html>`;
  return Buffer.from(html, 'utf8');
}
